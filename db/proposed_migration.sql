-- PROPOSED MIGRATION - for DB team review. NOT part of the current system.
-- Adds the data the Data Assistant needs to answer audit, confirmation, loss and AOD questions
-- (requirements 8.10 and 8.12). Table and column names are suggestions; adjust to your conventions.
-- If your real system already stores this elsewhere, tell us the tables and we will point the queries at them.
BEGIN;

CREATE TABLE asset_management.audit_cycles (
    cycle_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         varchar(150) NOT NULL,
    start_date   date NOT NULL,
    end_date     date NOT NULL,
    status       varchar(20) NOT NULL DEFAULT 'Active',
    CONSTRAINT ck_audit_cycles_status CHECK (status IN ('Active', 'Closed')),
    CONSTRAINT ck_audit_cycles_dates  CHECK (end_date >= start_date)
);

-- One row per asset per cycle: the self-confirmation request sent to the holder.
CREATE TABLE asset_management.audit_confirmations (
    confirmation_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id         bigint NOT NULL REFERENCES asset_management.audit_cycles(cycle_id) ON DELETE CASCADE,
    asset_id         bigint NOT NULL REFERENCES asset_management.assets(asset_id) ON DELETE CASCADE,
    user_id          bigint REFERENCES asset_management.users(user_id) ON DELETE SET NULL,
    requested_date   timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    due_date         date NOT NULL,
    responded_date   timestamptz,
    status           varchar(20) NOT NULL DEFAULT 'Pending',
    exception_reason text,
    CONSTRAINT ck_audit_conf_status CHECK (status IN ('Pending', 'Confirmed', 'Exception')),
    CONSTRAINT ux_audit_conf_cycle_asset UNIQUE (cycle_id, asset_id)
);
CREATE INDEX ix_audit_conf_status ON asset_management.audit_confirmations (status);
CREATE INDEX ix_audit_conf_asset  ON asset_management.audit_confirmations (asset_id);

-- Loss / theft cases (requirement 8.10).
CREATE TABLE asset_management.loss_cases (
    case_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id      bigint NOT NULL REFERENCES asset_management.assets(asset_id) ON DELETE CASCADE,
    user_id       bigint REFERENCES asset_management.users(user_id) ON DELETE SET NULL,
    case_type     varchar(20) NOT NULL,
    is_negligent  boolean NOT NULL DEFAULT false,
    reported_date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status        varchar(20) NOT NULL DEFAULT 'Open',
    CONSTRAINT ck_loss_cases_type   CHECK (case_type IN ('Lost', 'Stolen')),
    CONSTRAINT ck_loss_cases_status CHECK (status IN ('Open', 'Closed'))
);

-- Acknowledgement of Debt, generated when a case is marked Negligent (BR-8.10-03).
CREATE TABLE asset_management.aod_records (
    aod_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id       bigint NOT NULL REFERENCES asset_management.loss_cases(case_id) ON DELETE CASCADE,
    asset_id      bigint NOT NULL REFERENCES asset_management.assets(asset_id) ON DELETE CASCADE,
    user_id       bigint NOT NULL REFERENCES asset_management.users(user_id),
    amount        numeric(18,2) NOT NULL CHECK (amount >= 0),
    status        varchar(20) NOT NULL DEFAULT 'Open',
    created_date  timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_aod_status CHECK (status IN ('Open', 'Recovered', 'Written off'))
);

COMMIT;
